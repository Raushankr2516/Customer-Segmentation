def customer_segment(row):
    if row['Cluster'] == 0:
        return 'Loyal Customers'
    elif row['Cluster'] == 1:
        return 'New Customers'
    elif row['Cluster'] == 2:
        return 'Potential Customers'
    else:
        return 'At Risk Customers'

rfm['CustomerType'] = rfm.apply(customer_segment, axis=1)

